# Bytes of one ``(nmo, nmo, k_chunk)`` local B block. The default keeps the
# per-rank B workspace at 64 MiB (counted in elements of the amplitude dtype).
DEFAULT_K_CHUNK_BYTES = 64 * 1024 * 1024


def _root_global(group: Optional[Any]) -> int:
    """Global rank of the group's rank 0 (``0`` for the world group).

    ``gather_object`` and ``broadcast`` name their source as a global rank even
    when a group is passed, so the group's root has to be mapped explicitly.
    """
    if group is None:
        return 0
    return int(_dist().get_global_rank(group, 0))


def gather_spinless_amplitudes(
    x_local: Tensor,
    owned_index: Tensor,
    n_dets: int,
    *,
    group: Optional[Any] = None,
) -> Tensor:
    """Gather a scattered amplitude block into the full spinless vector on rank 0.

    Every rank contributes its owned ``(global index, value)`` pairs; rank 0 of
    ``group`` scatters them into one ``(n_dets,)`` vector and every other rank
    returns an empty tensor. The exchange is one ``gather_object``, the same
    pickled object collective used to collect the pair/spinless result blocks,
    so real and complex values need no real/imag split and no subcommunicators
    are created.

    Args:
        x_local: ``(n_local,)`` owned amplitude block, in ``owned_index`` order.
        owned_index: ``(n_local,)`` sorted global determinant positions, as
            ``SpinlessTileBounds.determinant_index`` or the ``arange`` of a
            contiguous owner-computes block.
        n_dets: Global determinant count.
        group: Optional process group; defaults to the world group.

    Returns:
        On rank 0 of ``group``, the ``(n_dets,)`` vector with every owned entry
        scattered into place (zeros elsewhere); on every other rank, a
        zero-length tensor of the same dtype and device.

    Raises:
        ValueError: ``x_local`` is not one-dimensional, its length disagrees
            with ``owned_index``, or an index lies outside ``[0, n_dets)``.
    """
    rank, world_size = _resolve_rank_world(None, None, group)
    n_dets = int(n_dets)
    if x_local.dim() != 1:
        raise ValueError(f"x_local must be 1-D, got shape {tuple(x_local.shape)}")
    index = owned_index.detach().reshape(-1).to(device=x_local.device, dtype=torch.int64)
    if index.numel() != x_local.numel():
        raise ValueError(
            f"owned_index has {index.numel()} entries but x_local has {x_local.numel()}"
        )
    if index.numel() and (int(index.min()) < 0 or int(index.max()) >= n_dets):
        raise ValueError(f"owned_index must lie in [0, {n_dets})")

    if world_size == 1:
        full = torch.zeros(n_dets, dtype=x_local.dtype, device=x_local.device)
        full[index] = x_local
        return full

    dist = _dist()
    payload = (index.detach().cpu(), x_local.detach().cpu())
    gathered: Optional[list[Any]] = [None] * world_size if rank == 0 else None
    dist.gather_object(payload, gathered, dst=_root_global(group), group=group)
    if rank != 0:
        return torch.empty(0, dtype=x_local.dtype, device=x_local.device)

    assert gathered is not None
    full = torch.zeros(n_dets, dtype=x_local.dtype, device=x_local.device)
    for peer_index, values in gathered:
        full[peer_index.to(device=x_local.device)] = values.to(
            device=x_local.device, dtype=x_local.dtype
        )
    return full


def _broadcast_result(tensor: Tensor, root: int, group: Optional[Any]) -> None:
    """Broadcast a small result tensor in place, splitting complex values.

    Complex tensors travel as their interleaved real view, the packing
    :meth:`~torch_sci_solver.torch_impl.distributed_davidson.DistributedVector.
    to_global` uses, because some backends have no complex scalar type.
    """
    payload = torch.view_as_real(tensor).view(-1) if tensor.is_complex() else tensor.view(-1)
    _dist().broadcast(payload, src=root, group=group)


def can_partition_spinless_rdm(
    basis: SpinlessBasis,
    *,
    world_size: Optional[int] = None,
    dtype: torch.dtype = torch.float64,
    max_local_bytes: Optional[int] = None,
) -> bool:
    """Whether the spinless full 2-RDM output can be accumulated partitioned.

    Args:
        basis: The flat determinant list.
        world_size: Ranks to partition over; defaults to the initialized group.
        dtype: Output dtype used for the byte estimate.
        max_local_bytes: Optional largest acceptable per-rank ``nmo**4`` slice.

    Returns:
        True when the output can be split across at least one rank and the
        optional byte bound is met.
    """
    nmo = int(basis.n_spinorb)
    if nmo <= 0:
        return False
    try:
        _rank, world = _resolve_rank_world(None, world_size, None)
    except ValueError:
        return False
    if world <= 0:
        return False
    n = nmo**4
    local = (n + world - 1) // world
    if max_local_bytes is not None and local * tensor_itemsize(dtype) > int(max_local_bytes):
        return False
    return True


def _owned_positions(owned_sorted: Tensor, index: Tensor) -> tuple[Tensor, Tensor]:
    """Map global selected positions to positions in an owned, sorted block.

    Args:
        owned_sorted: ``(n_local,)`` ascending global selected positions.
        index: ``(k,)`` global selected positions to look up.

    Returns:
        ``(position, found)``. ``position`` is clamped into range; ``found``
        marks the entries that are owned.
    """
    if owned_sorted.numel() == 0:
        empty = torch.zeros(index.shape, dtype=torch.long, device=index.device)
        return empty, torch.zeros(index.shape, dtype=torch.bool, device=index.device)
    position = torch.searchsorted(owned_sorted, index)
    clipped = position.clamp(max=owned_sorted.numel() - 1)
    return clipped, (position < owned_sorted.numel()) & (owned_sorted[clipped] == index)


def _k_chunk_size(nmo: int, dtype: torch.dtype, k_chunk_bytes: int) -> int:
    """Connected-axis chunk width for one local ``B`` block.

    Args:
        nmo: Number of spin-orbitals.
        dtype: Amplitude dtype.
        k_chunk_bytes: Byte budget of the ``(nmo, nmo, k_chunk)`` block.

    Returns:
        The chunk width in connected-set columns, at least one.
    """
    per_column = max(1, nmo * nmo * tensor_itemsize(dtype))
    return max(1, int(k_chunk_bytes) // per_column)


def _k_ranges(n_connected: int, width: int) -> tuple[tuple[int, int], ...]:
    """Split ``[0, n_connected)`` into fixed-width chunks."""
    return tuple((start, min(start + width, n_connected)) for start in range(0, n_connected, width))


def _diagonal_b_chunk(
    basis: SpinlessBasis,
    x_local: Tensor,
    owned_sorted: Tensor,
    owned_conn: Tensor,
    k0: int,
    k1: int,
    nmo: int,
) -> Tensor:
    """Local diagonal contribution ``B[p, p, K] = occ(K, p) C_K`` of one chunk.

    Args:
        basis: The flat determinant list.
        x_local: ``(n_local,)`` owned amplitudes, in ``owned_sorted`` order.
        owned_sorted: ``(n_local,)`` ascending global selected positions.
        owned_conn: ``(n_local,)`` connected-set position of each owned
            selected determinant.
        k0: First connected column of the chunk (inclusive).
        k1: One past the last connected column of the chunk.
        nmo: Number of spin-orbitals.

    Returns:
        ``(nmo, nmo, k1 - k0)`` local diagonal block.
    """
    device = x_local.device
    dtype = x_local.dtype
    chunk = torch.zeros((nmo, nmo, k1 - k0), dtype=dtype, device=device)
    chosen = torch.nonzero((owned_conn >= k0) & (owned_conn < k1), as_tuple=False).reshape(-1)
    if chosen.numel() == 0:
        return chunk
    dets = basis.dets[owned_sorted[chosen]]
    n_limbs = int(dets.shape[-1])
    p_range = torch.arange(nmo, dtype=torch.int64, device=device)
    occ = getocc_batch(
        dets.unsqueeze(-2).expand(dets.shape[0], nmo, n_limbs),
        None,
        p_range.expand(dets.shape[0], nmo),
    ).to(dtype)
    values = occ * x_local[chosen].unsqueeze(-1)
    columns = (owned_conn[chosen] - k0).unsqueeze(-1)
    chunk[p_range.unsqueeze(0), p_range.unsqueeze(0), columns] = values
    return chunk


def _singles_b_chunk(
    basis: SpinlessBasis,
    helpers: SpinlessHelpers,
    connected: Tensor,
    x_local: Tensor,
    owned_sorted: Tensor,
    k0: int,
    k1: int,
    chunk: Tensor,
) -> None:
    """Scatter the owned-amplitude singles rows of one connected chunk.

    Args:
        basis: The flat determinant list.
        helpers: Streaming table accessor (supplies the enumeration budget).
        connected: The full connected determinant list.
        x_local: ``(n_local,)`` owned amplitudes, in ``owned_sorted`` order.
        owned_sorted: ``(n_local,)`` ascending global selected positions.
        k0: First connected column of the chunk (inclusive).
        k1: One past the last connected column of the chunk.
        chunk: ``(nmo, nmo, k1 - k0)`` local block updated in place.
    """
    stream = _stream_spinless(
        dets=basis.dets,
        n_spinorb=basis.n_spinorb,
        n_particles=basis.n_particles,
        order=1,
        device=basis.device,
        budget_bytes=helpers.budget_bytes,
        src_dets=connected[k0:k1],
        target_dets=basis.dets,
    )
    for table in stream:
        sign, k_bra, k_ket, cr, an = _singles_sign_and_indices(basis, table)
        position, owned = _owned_positions(owned_sorted, k_ket.to(owned_sorted.device))
        if not bool(owned.any()):
            continue
        contribution = sign[owned].to(x_local.dtype) * x_local[position[owned]]
        chunk.index_put_(
            (an[owned], cr[owned], k_bra[owned]),
            contribution,
            accumulate=True,
        )


def _spinless_rdm12_partitioned(
    basis: SpinlessBasis,
    helpers: SpinlessHelpers,
    x_local: Tensor,
    owned_index: Tensor,
    *,
    rank: int,
    world_size: int,
    group: Optional[Any],
    k_chunk_bytes: int,
) -> tuple[PartitionedRDM, PartitionedRDM]:
    """Build both RDMs with the output partitioned across the ranks.

    Every ``B`` chunk is summed across the ranks, so each rank holds the
    complete single-excitation tensor for the chunk and forms only the Gram
    rows of its own output slice. The full ``nmo**4`` Gram is never allocated.

    Args:
        basis: The global flat determinant list.
        helpers: Excitation-table streamer for ``basis``.
        x_local: ``(n_local,)`` owned amplitude block.
        owned_index: ``(n_local,)`` global determinant positions.
        rank: This rank in ``[0, world_size)``.
        world_size: Number of ranks.
        group: Process group of the reductions.
        k_chunk_bytes: Byte budget of one local ``B`` block.

    Returns:
        ``(rdm1, rdm2)`` partitioned behind :class:`PartitionedRDM`.
    """
    nmo = int(basis.n_spinorb)
    device = x_local.device
    dtype = x_local.dtype
    order = torch.argsort(owned_index.reshape(-1).to(device=device, dtype=torch.int64))
    owned_sorted = owned_index.reshape(-1).to(device=device, dtype=torch.int64)[order]
    owned_amplitudes = x_local.reshape(-1)[order]

    connected, _chunks = helpers.connected_singles()
    _found, sel_rows = _found_in_multilimb(connected, basis.dets)
    owned_conn = sel_rows[owned_sorted]

    partition = build_output_partition(nmo**4, world_size, rank)
    n_columns = nmo * nmo
    if partition.local_size:
        row_lo = partition.start // n_columns
        row_hi = (partition.stop - 1) // n_columns + 1
    else:
        row_lo = row_hi = 0
    gram = torch.zeros((row_hi - row_lo, n_columns), dtype=dtype, device=device)

    dm1 = torch.zeros((nmo, nmo), dtype=dtype, device=device)
    width = _k_chunk_size(nmo, dtype, k_chunk_bytes)
    for k0, k1 in _k_ranges(int(connected.shape[0]), width):
        chunk = _diagonal_b_chunk(basis, owned_amplitudes, owned_sorted, owned_conn, k0, k1, nmo)
        _singles_b_chunk(
            basis,
            helpers,
            connected,
            owned_amplitudes,
            owned_sorted,
            k0,
            k1,
            chunk,
        )
        GlobalSum(group).all_reduce(chunk)
        chosen = torch.nonzero((owned_conn >= k0) & (owned_conn < k1), as_tuple=False).reshape(-1)
        if chosen.numel():
            dm1 = dm1 + torch.einsum(
                "pqk,k->pq",
                chunk[:, :, owned_conn[chosen] - k0],
                owned_amplitudes[chosen].conj(),
            )
        flat_b = chunk.reshape(n_columns, k1 - k0)
        flat_bt = chunk.permute(1, 0, 2).reshape(n_columns, k1 - k0)
        gram.addmm_(flat_bt[row_lo:row_hi].conj(), flat_b.T)
    GlobalSum(group).all_reduce(dm1)

    offset = partition.start - row_lo * n_columns
    local = gram.reshape(-1)[offset : offset + partition.local_size]
    if partition.local_size:
        index = torch.arange(partition.start, partition.stop, dtype=torch.int64, device=device)
        s = index % nmo
        r = (index // nmo) % nmo
        q = (index // n_columns) % nmo
        p = index // (nmo**3)
        diagonal = q == r
        if bool(diagonal.any()):
            local[diagonal] = local[diagonal] - dm1[p[diagonal], s[diagonal]]

    rdm1_partition = build_output_partition(n_columns, world_size, rank)
    rdm1 = PartitionedRDM(
        data=dm1.reshape(-1)[rdm1_partition.start : rdm1_partition.stop],
        partition=rdm1_partition,
        shape=(nmo, nmo),
    )
    rdm2 = PartitionedRDM(data=local, partition=partition, shape=(nmo, nmo, nmo, nmo))
    return rdm1, rdm2


def _spinless_rdm12_replicated(
    basis: SpinlessBasis,
    helpers: SpinlessHelpers,
    x_local: Tensor,
    owned_index: Tensor,
    *,
    group: Optional[Any],
    chunk_size: int,
) -> tuple[Tensor, Tensor]:
    """Previous gather-then-serial implementation, kept as the small-case path.

    Args:
        basis: the global flat determinant list.
        helpers: excitation-table streamer for ``basis``.
        x_local: ``(n_local,)`` owned amplitude block.
        owned_index: ``(n_local,)`` sorted global determinant positions.
        group: Optional process group.
        chunk_size: forwarded to :func:`spinless_rdm12_torch`.

    Returns:
        ``(rdm1, rdm2)`` on every rank.
    """
    rank, world_size = _resolve_rank_world(None, None, group)
    full = gather_spinless_amplitudes(x_local, owned_index, basis.dim, group=group)
    if world_size == 1:
        return spinless_rdm12_torch(basis, helpers, full, chunk_size=chunk_size)

    nmo = basis.n_spinorb
    dtype = x_local.dtype
    device = x_local.device
    if rank == 0:
        rdm1, rdm2 = spinless_rdm12_torch(basis, helpers, full, chunk_size=chunk_size)
    else:
        rdm1 = torch.empty((nmo, nmo), dtype=dtype, device=device)
        rdm2 = torch.empty((nmo, nmo, nmo, nmo), dtype=dtype, device=device)
    root = _root_global(group)
    _broadcast_result(rdm1, root, group)
    _broadcast_result(rdm2, root, group)
    return rdm1, rdm2


def spinless_rdm12_distributed(
    basis: SpinlessBasis,
    helpers: SpinlessHelpers,
    x_local: Tensor,
    owned_index: Tensor,
    *,
    group: Optional[Any] = None,
    chunk_size: int = DEFAULT_CHUNK_SIZE,
    replicate: bool = True,
    max_replicated_bytes: int = DEFAULT_MAX_REPLICATED_BYTES,
    k_chunk_bytes: int = DEFAULT_K_CHUNK_BYTES,
) -> tuple[Tensor, Tensor] | tuple[PartitionedRDM, PartitionedRDM]:
    """1- and 2-RDM of a scattered spinless solution block.

    Each rank contributes the ``B`` entries generated by its owned amplitudes;
    the connected-set ``K`` axis is reduced in fixed chunks and the
    ``nmo**4`` Gram output is accumulated one owner group at a time, so no rank
    ever holds the full amplitude vector or the full ``nmo**4`` block.

    Args:
        basis: the global flat determinant list.
        helpers: excitation-table streamer for ``basis``.
        x_local: ``(n_local,)`` owned amplitude block, in ``owned_index`` order.
        owned_index: ``(n_local,)`` global determinant positions.
        group: Optional process group; defaults to the world group.
        chunk_size: forwarded to the replicated fallback's serial builder.
        replicate: Return ``(rdm1, rdm2)`` on every rank. ``False`` returns the
            two partitioned handles.
        max_replicated_bytes: Full ``nmo**4`` byte bound below which the
            gather-then-serial fallback is used verbatim.
        k_chunk_bytes: Byte budget of one local ``(nmo, nmo, k)`` B block.

    Returns:
        ``(rdm1, rdm2)`` when ``replicate`` is True: ``rdm1`` is ``(nmo, nmo)``
        and ``rdm2`` is ``(nmo, nmo, nmo, nmo)``, both in the amplitude dtype.
        Otherwise the two :class:`PartitionedRDM` handles.

    Raises:
        ValueError: ``x_local`` does not have one entry per owned determinant.
    """
    rank, world_size = _resolve_rank_world(None, None, group)
    nmo = int(basis.n_spinorb)
    if x_local.dim() != 1 or x_local.numel() != owned_index.numel():
        raise ValueError(
            f"x_local shape {tuple(x_local.shape)} disagrees with "
            f"owned_index ({owned_index.numel()} entries)"
        )
    if replicate and should_replicate(
        nmo**4,
        x_local.dtype,
        world_size=world_size,
        max_replicated_bytes=max_replicated_bytes,
    ):
        return _spinless_rdm12_replicated(
            basis, helpers, x_local, owned_index, group=group, chunk_size=chunk_size
        )

    rdm1_part, rdm2_part = _spinless_rdm12_partitioned(
        basis,
        helpers,
        x_local,
        owned_index,
        rank=rank,
        world_size=world_size,
        group=group,
        k_chunk_bytes=k_chunk_bytes,
    )
    if not replicate:
        return rdm1_part, rdm2_part
    return rdm1_part.gather(group=group), rdm2_part.gather(group=group)
