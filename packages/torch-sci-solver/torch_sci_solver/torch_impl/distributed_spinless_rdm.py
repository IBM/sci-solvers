"""Distributed spinless 1-/2-RDM construction from owned amplitude blocks.

The owner-computes spinless Davidson keeps only the owned determinant block of
every vector on each rank. The replicated RDM path used to reassemble the full
amplitude vector on rank 0 and run the serial Gram builder there; this module
now builds the same RDMs from the owned blocks directly.

The algorithm mirrors :func:`~torch_sci_solver.torch_impl.rdm_spinless.
spinless_rdm12_torch`, which builds the single-excitation tensor
``B[p, q, K] = <D_K| a_p^ a_q |C>`` over the *connected set* ``K`` (the
selected determinants plus every single-excitation reachable target), then
``dm1[p,q] = sum_K conj(C_K) B[p,q,K]`` and the Gram term
``T[p,q,r,s] = sum_K conj(B[q,p,K]) B[r,s,K]``, followed by the
``dm2[:, q, q, :] -= dm1`` correction.

Distribution
------------
Every ``B`` entry is generated by the rank owning the source amplitude
``C_K``: the diagonal term uses the owned selected determinants, and a singles
table row ``k_bra -> k_ket`` is kept only when ``k_ket`` is owned, contributing
``sgn C[k_ket]`` at ``B[an, cr, k_bra]``. The connected-set axis is processed
in fixed column chunks; each chunk's local ``B`` block is summed with one
``all_reduce(SUM)``, and every rank then forms only the Gram rows that cover
its own ``nmo**4 / world_size`` output slice. The full amplitude vector and the
full Gram matrix are never materialised on any rank.

Collective order
----------------
For a chunk plan derived purely from ``(nmo, k_chunk_bytes)`` (and the output
partition, a pure function of ``(nmo**4, world_size, rank)``) every rank
performs, in order: one ``all_reduce(SUM)`` of each ``B`` chunk, then one
``all_reduce(SUM)`` of the small ``dm1`` partial. The Gram rows are built from
the already-reduced ``B`` chunk, so each rank keeps its own output slice
without a further output reduction. The number of collectives depends only on
the connected-set size and the chunk width, never on rank-local data. Complex
payloads travel through :class:`GlobalSum`'s interleaved real view.

Fallback
--------
:func:`spinless_rdm12_distributed` keeps the previous gather-then-serial
implementation and selects it whenever the full ``nmo**4`` output fits
``max_replicated_bytes`` (or the group has one rank), so the small case stays
bit-identical. :func:`can_partition_spinless_rdm` is the preflight predicate.
"""

